"""
Run every query in sql/analysis/, save each result to results/<name>.csv,
and write results/SUMMARY.md with a preview table per question.

Usage:  python scripts/run_analysis.py
        python scripts/run_analysis.py q05      (run only queries whose name starts with q05)
"""
import csv
import sys
from decimal import Decimal
from pathlib import Path

from db import get_connection

ROOT = Path(__file__).resolve().parent.parent
QUERY_DIR = ROOT / "sql" / "analysis"
RESULTS_DIR = ROOT / "results"
PREVIEW_ROWS = 20


def title_of(sql_text):
    """First comment line, e.g. '-- Q1. How are revenue ...' -> 'Q1. How are revenue ...'"""
    for line in sql_text.splitlines():
        if line.startswith("--"):
            return line.lstrip("- ").strip()
    return ""


def fmt(value):
    if value is None:
        return ""
    if isinstance(value, Decimal):
        return f"{value:,}" if abs(value) >= 1000 else str(value)
    return str(value)


def to_markdown(columns, rows):
    lines = ["| " + " | ".join(columns) + " |", "|" + "---|" * len(columns)]
    for row in rows[:PREVIEW_ROWS]:
        lines.append("| " + " | ".join(fmt(v) for v in row) + " |")
    if len(rows) > PREVIEW_ROWS:
        lines.append(f"\n_{len(rows) - PREVIEW_ROWS} more rows in the CSV._")
    return "\n".join(lines)


def main():
    prefix = sys.argv[1] if len(sys.argv) > 1 else ""
    files = sorted(p for p in QUERY_DIR.glob("*.sql") if p.name.startswith(prefix))
    if not files:
        sys.exit(f"No queries found matching '{prefix}'")
    RESULTS_DIR.mkdir(exist_ok=True)

    summary = ["# Results\n", "Generated by `scripts/run_analysis.py`.\n"]
    conn = get_connection()
    try:
        with conn.cursor() as cur:
            for path in files:
                sql = path.read_text(encoding="utf-8")
                cur.execute(sql)
                columns = [d[0] for d in cur.description]
                rows = cur.fetchall()

                with open(RESULTS_DIR / f"{path.stem}.csv", "w", newline="", encoding="utf-8") as f:
                    writer = csv.writer(f)
                    writer.writerow(columns)
                    writer.writerows(rows)

                summary += [f"## {title_of(sql)}\n", f"Query: `sql/analysis/{path.name}`\n",
                            to_markdown(columns, rows), ""]
                print(f"{path.stem:<36} {len(rows):>5} rows")
    finally:
        conn.close()

    if not prefix:
        (RESULTS_DIR / "SUMMARY.md").write_text("\n".join(summary), encoding="utf-8")
        print(f"\nPreview of every result: {RESULTS_DIR / 'SUMMARY.md'}")


if __name__ == "__main__":
    main()
